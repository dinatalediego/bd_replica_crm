-- Model/data quality gates for local Medallio datasets.
-- Stores aggregate evidence only; never persist source rows or customer PII here.

CREATE SCHEMA IF NOT EXISTS model_control;

CREATE TABLE IF NOT EXISTS model_control.data_quality_test_catalog (
    test_id        text PRIMARY KEY,
    suite_key      text NOT NULL,
    dataset_key    text NOT NULL,
    description    text NOT NULL,
    severity       text NOT NULL CHECK (severity IN ('BLOCK', 'WARN')),
    is_required    boolean NOT NULL DEFAULT true,
    enabled        boolean NOT NULL DEFAULT true,
    updated_at     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS model_control.data_quality_suite_run (
    run_id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    suite_key       text NOT NULL,
    dataset_key     text NOT NULL,
    started_at      timestamptz NOT NULL DEFAULT now(),
    completed_at    timestamptz,
    run_status      text NOT NULL CHECK (run_status IN ('RUNNING', 'PASS', 'WARN', 'BLOCK', 'ERROR')),
    code_revision   text,
    runner_version  text NOT NULL,
    summary         jsonb NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS ix_data_quality_suite_run_latest
    ON model_control.data_quality_suite_run (dataset_key, completed_at DESC, run_id DESC);

CREATE TABLE IF NOT EXISTS model_control.data_quality_test_result (
    run_id          bigint NOT NULL REFERENCES model_control.data_quality_suite_run(run_id) ON DELETE CASCADE,
    test_id         text NOT NULL REFERENCES model_control.data_quality_test_catalog(test_id),
    result_status   text NOT NULL CHECK (result_status IN ('PASS', 'WARN', 'FAIL', 'BLOCKED')),
    exception_count bigint NOT NULL DEFAULT 0 CHECK (exception_count >= 0),
    observed_value  jsonb NOT NULL DEFAULT '{}'::jsonb,
    threshold_value jsonb NOT NULL DEFAULT '{}'::jsonb,
    details         text NOT NULL,
    evaluated_at    timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (run_id, test_id)
);

CREATE TABLE IF NOT EXISTS model_control.training_dataset_manifest (
    manifest_id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id                      bigint NOT NULL REFERENCES model_control.data_quality_suite_run(run_id) ON DELETE CASCADE,
    dataset_key                 text NOT NULL,
    source_relation             text NOT NULL,
    grain_columns               text[] NOT NULL,
    target_column               text,
    observation_time_column     text,
    source_row_count             bigint NOT NULL CHECK (source_row_count >= 0),
    eligible_row_count           bigint NOT NULL CHECK (eligible_row_count >= 0),
    excluded_row_count            bigint NOT NULL CHECK (excluded_row_count >= 0),
    window_start                  date,
    window_end                    date,
    contract_sha256               text NOT NULL,
    aggregate_signature_sha256    text NOT NULL,
    gate_status                   text NOT NULL CHECK (gate_status IN ('PASS', 'WARN', 'BLOCK', 'ERROR')),
    evidence                      jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at                    timestamptz NOT NULL DEFAULT now(),
    UNIQUE (run_id, dataset_key)
);

