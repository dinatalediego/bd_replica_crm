CREATE OR REPLACE VIEW model_control.v_model_data_quality_latest_gate AS
WITH datasets AS (
    SELECT DISTINCT suite_key, dataset_key
    FROM model_control.data_quality_test_catalog
    WHERE enabled
), latest AS (
    SELECT DISTINCT ON (dataset_key)
        run_id, suite_key, dataset_key, run_status, started_at, completed_at,
        code_revision, runner_version, summary
    FROM model_control.data_quality_suite_run
    WHERE completed_at IS NOT NULL
    ORDER BY dataset_key, completed_at DESC, run_id DESC
), counts AS (
    SELECT
        l.dataset_key,
        count(*) FILTER (WHERE c.enabled AND c.is_required) AS expected_tests,
        count(r.test_id) FILTER (
            WHERE c.enabled AND c.is_required AND r.result_status <> 'BLOCKED'
        ) AS executed_tests,
        count(*) FILTER (WHERE r.result_status = 'FAIL') AS failed_tests,
        count(*) FILTER (WHERE r.result_status = 'WARN') AS warning_tests,
        count(*) FILTER (WHERE r.result_status = 'BLOCKED') AS blocked_tests,
        coalesce(sum(r.exception_count), 0) AS total_exceptions
    FROM latest l
    LEFT JOIN model_control.data_quality_test_catalog c
      ON c.dataset_key = l.dataset_key AND c.enabled
    LEFT JOIN model_control.data_quality_test_result r
      ON r.run_id = l.run_id AND r.test_id = c.test_id
    GROUP BY l.dataset_key
)
SELECT
    d.suite_key,
    d.dataset_key,
    l.run_id,
    l.started_at,
    l.completed_at,
    l.code_revision,
    l.runner_version,
    coalesce(c.expected_tests, 0) AS expected_tests,
    coalesce(c.executed_tests, 0) AS executed_tests,
    coalesce(c.failed_tests, 0) AS failed_tests,
    coalesce(c.warning_tests, 0) AS warning_tests,
    coalesce(c.blocked_tests, 0) AS blocked_tests,
    coalesce(c.total_exceptions, 0) AS total_exceptions,
    CASE
        WHEN l.run_id IS NULL THEN 'NO_RUN'
        WHEN coalesce(c.executed_tests, 0) <> coalesce(c.expected_tests, 0)
          OR coalesce(c.blocked_tests, 0) > 0
          OR coalesce(c.failed_tests, 0) > 0
          OR l.run_status IN ('BLOCK', 'ERROR') THEN 'BLOCK'
        WHEN coalesce(c.warning_tests, 0) > 0 OR l.run_status = 'WARN' THEN 'WARN'
        ELSE 'PASS'
    END AS data_quality_status,
    l.summary
FROM datasets d
LEFT JOIN latest l ON l.dataset_key = d.dataset_key
LEFT JOIN counts c ON c.dataset_key = d.dataset_key;

CREATE OR REPLACE VIEW model_control.v_model_data_quality_latest_results AS
WITH latest AS (
    SELECT DISTINCT ON (dataset_key) run_id, dataset_key
    FROM model_control.data_quality_suite_run
    WHERE completed_at IS NOT NULL
    ORDER BY dataset_key, completed_at DESC, run_id DESC
)
SELECT
    r.run_id, c.suite_key, c.dataset_key, r.test_id, c.description,
    c.severity, c.is_required, r.result_status, r.exception_count,
    r.observed_value, r.threshold_value, r.details, r.evaluated_at
FROM model_control.data_quality_test_result r
JOIN latest l ON l.run_id = r.run_id
JOIN model_control.data_quality_test_catalog c ON c.test_id = r.test_id;

COMMENT ON VIEW model_control.v_model_data_quality_latest_gate IS
'Latest data-quality readiness by dataset. This gate does not certify predictive performance or model release.';

COMMENT ON TABLE model_control.training_dataset_manifest IS
'Aggregate-only manifest for reproducibility: source, grain, target, time window, contract hash and quality evidence; no source rows or customer PII.';
